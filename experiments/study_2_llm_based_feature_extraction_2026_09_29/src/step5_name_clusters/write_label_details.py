"""Draft feature list generated from named clusters."""

from __future__ import annotations

import json
import re

import pandas as pd

from experiments.study_2_llm_based_feature_extraction_2026_09_29.shared.constants import (
    LABEL_KEY_PREFIX,
)

_NON_SLUG = re.compile(r"[^a-z0-9]+")


def label_key(name: str) -> str:
    """Turn a cluster name into an ``is_`` feature key.

    Parameters
    ----------
    name
        Cluster name from the naming model.

    Returns
    -------
    str
        Lowercase key with non-letters collapsed to one underscore.
    """
    slug = _NON_SLUG.sub("_", name.lower()).strip("_")
    return f"{LABEL_KEY_PREFIX}{slug}"


def build_label_to_detail(review: pd.DataFrame) -> dict[str, dict[str, str]]:
    """Build the feature mapping, resolving duplicate keys in cluster-key order.

    Parameters
    ----------
    review
        Review table with ``cluster_key``, ``name``, and ``definition``.

    Returns
    -------
    dict[str, dict[str, str]]
        Feature key to ``name`` and ``description``. The second collision
        gets ``_2``, the third ``_3``, and so on.
    """
    mapping: dict[str, dict[str, str]] = {}
    seen: dict[str, int] = {}
    ordered = review.sort_values("cluster_key")
    for _, row in ordered.iterrows():
        base = label_key(str(row["name"]))
        seen[base] = seen.get(base, 0) + 1
        key = base if seen[base] == 1 else f"{base}_{seen[base]}"
        mapping[key] = {
            "name": str(row["name"]),
            "description": str(row["definition"]),
        }
    return mapping


def render_label_details_module(mapping: dict[str, dict[str, str]]) -> str:
    """Render the hand-reviewed feature module.

    Parameters
    ----------
    mapping
        Output of :func:`build_label_to_detail`.

    Returns
    -------
    str
        Python source with ``LABEL_TO_DETAIL`` keys sorted.
    """
    body = json.dumps(dict(sorted(mapping.items())), indent=2, ensure_ascii=False)
    return (
        '"""Draft cluster names for Study 2.\n\n'
        "Generated by experiments.study_2_llm_based_feature_extraction_2026_09_29"
        ".src.step5_name_clusters.run. Review this file by hand before step 6.\n"
        '"""\n\n'
        f"LABEL_TO_DETAIL: dict[str, dict[str, str]] = {body}\n"
    )


def validate_label_to_detail(mapping: dict[str, dict[str, str]]) -> None:
    """Reject a feature mapping that step 6 cannot read.

    Parameters
    ----------
    mapping
        Feature key to ``name`` and ``description``.

    Raises
    ------
    ValueError
        When a key, name, or description does not match the contract.
    """
    for key, value in mapping.items():
        if not str(key).startswith(LABEL_KEY_PREFIX):
            raise ValueError(f"key must start with {LABEL_KEY_PREFIX}: {key}")
        if set(value) != {"name", "description"}:
            raise ValueError(f"value keys must be name and description: {key}")
        if not str(value["name"]).strip() or not str(value["description"]).strip():
            raise ValueError(f"name and description must be non-empty: {key}")
